#!/usr/bin/env node
// Generates the CloudFormation templates in aws/ from the shared DUPR sources.
//
//   aws/dupr-template.yaml        Lambda + public Function URL  (all-in-one, 60 s Lambda timeout,
//                                 the function also serves the page at "/")
//   aws/dupr-apigw-template.yaml  Lambda + API Gateway HTTP API (call the API from a page you host
//                                 somewhere else; API Gateway caps an integration at 30 s)
//
// The function code is inlined (CloudFormation Code.ZipFile) and built from:
//   - tools/dupr/app.mjs      shared core    (export keywords stripped, concatenated first)
//   - tools/dupr/lambda.mjs   Lambda adapter (import line stripped, exports.handler appended)
//   - tools/dupr/index.html   the page, base64 so "/" still answers (handy while debugging)
//
// Re-run after editing any of those:  npm run dupr:template
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..', '..');
const OUT_FUNCTION_URL = path.join(ROOT, 'aws', 'dupr-template.yaml');
const OUT_API_GATEWAY = path.join(ROOT, 'aws', 'dupr-apigw-template.yaml');

const stripModuleSyntax = (src) => src
  .replace(/^\s*import[^\n]*\n/gm, '')      // no imports in the bundle
  .replace(/^export\s+/gm, '')             // drop export keywords
  .replace(/\bexport const handler\b/, 'const handler');

const app = stripModuleSyntax(fs.readFileSync(path.join(HERE, 'app.mjs'), 'utf8'));
const lambda = stripModuleSyntax(fs.readFileSync(path.join(HERE, 'lambda.mjs'), 'utf8'));
const htmlB64 = fs.readFileSync(path.join(HERE, 'index.html')).toString('base64');

const code = [
  '// GENERATED by tools/dupr/build-template.mjs — edit tools/dupr/*.mjs and rebuild.',
  `const INDEX_HTML_B64 = ${JSON.stringify(htmlB64)};`,
  app,
  lambda,
  'exports.handler = handler;',
  '',
].join('\n');

if (/^\s*(import|export)\s/m.test(code)) {
  throw new Error('bundle still contains ESM syntax — tighten stripModuleSyntax()');
}

const indent = (text, spaces) => text.split('\n').map((line) => (line ? ' '.repeat(spaces) + line : '')).join('\n');

// ── shared pieces ────────────────────────────────────────────────────────────

const parameters = ({ maxPages = 3, timeout = 60, cookieOptional = false, timeoutNote = '' }) => `Parameters:
  DuprCookie:
    Type: String
    NoEcho: true
${cookieOptional ? "    Default: ''\n" : '    MinLength: 20\n'}    Description: >-
      DUPR session cookie line from dashboard.dupr.com DevTools, e.g.
      "__Host-dupr_at=eyJ...; __Host-dupr_rt=eyJ..." (a bare JWT also works).
${cookieOptional
    ? `      Optional here: leave it empty and every visitor supplies their own cookie through the
      page ("My cookie"). When set, it is the default for anyone who does not.`
    : `      This is the default session; visitors can still paste their own cookie in the page.`}

  ApiToken:
    Type: String
    NoEcho: true
    Default: ''
    Description: >-
      Optional shared secret. When set, every /api/* call must send it in the x-dupr-token
      header (the page asks for it once and remembers it). Leave empty for an open endpoint -
      not recommended, the function holds your personal DUPR session.

  AllowedOrigin:
    Type: String
    Default: '*'
    Description: >-
      Origin allowed by CORS - the site that hosts the page, e.g. https://you.github.io.
      Use '*' while testing.

  States:
    Type: String
    Default: 'CT,MA'
    Description: Comma-separated state codes used for the UI default location filter.

  SearchLat:
    Type: Number
    Default: 41.5623209
    Description: Latitude used to bias DUPR's proximity ordering (East Hartford Racquet Club).

  SearchLng:
    Type: Number
    Default: -72.6506488
    Description: Longitude used to bias DUPR's proximity ordering.

  MaxPages:
    Type: Number
    Default: ${maxPages}
    Description: Pages of 10 same-name hits scanned per name (raise it for very common names).

  CacheMinutes:
    Type: Number
    Default: 360
    Description: In-memory cache TTL per warm container.

  ThrottleMs:
    Type: Number
    Default: 250
    Description: Pause between consecutive DUPR requests.

  Timeout:
    Type: Number
    Default: ${timeout}
    Description: Lambda timeout in seconds.${timeoutNote}

  MemorySize:
    Type: Number
    Default: 512
    AllowedValues: [128, 256, 512, 1024]
`;

const coreResources = `  FunctionLogGroup:
    Type: AWS::Logs::LogGroup
    Properties:
      LogGroupName: !Sub '/aws/lambda/\${AWS::StackName}-dupr-lookup'
      RetentionInDays: 14

  FunctionRole:
    Type: AWS::IAM::Role
    Properties:
      AssumeRolePolicyDocument:
        Version: '2012-10-17'
        Statement:
          - Effect: Allow
            Principal:
              Service: lambda.amazonaws.com
            Action: sts:AssumeRole
      ManagedPolicyArns:
        - !Sub 'arn:\${AWS::Partition}:iam::aws:policy/service-role/AWSLambdaBasicExecutionRole'

  LookupFunction:
    Type: AWS::Lambda::Function
    Properties:
      FunctionName: !Sub '\${AWS::StackName}-dupr-lookup'
      Description: DUPR player search proxy (see tools/dupr)
      Runtime: nodejs22.x
      Handler: index.handler
      Architectures:
        - arm64
      Timeout: !Ref Timeout
      MemorySize: !Ref MemorySize
      Role: !GetAtt FunctionRole.Arn
      Environment:
        Variables:
          DUPR_COOKIE: !Ref DuprCookie
          DUPR_API_TOKEN: !Ref ApiToken
          DUPR_STATES: !Ref States
          DUPR_LAT: !Ref SearchLat
          DUPR_LNG: !Ref SearchLng
          DUPR_MAX_PAGES: !Ref MaxPages
          DUPR_CACHE_MINUTES: !Ref CacheMinutes
          DUPR_THROTTLE_MS: !Ref ThrottleMs
          ALLOWED_ORIGIN: !Ref AllowedOrigin
      Code:
        ZipFile: |
${indent(code, 10)}
    DependsOn: FunctionLogGroup
`;

// ── target A: Lambda Function URL ────────────────────────────────────────────

const functionUrlResources = `  FunctionUrl:
    Type: AWS::Lambda::Url
    Properties:
      TargetFunctionArn: !GetAtt LookupFunction.Arn
      AuthType: NONE
      InvokeMode: BUFFERED
      Cors:
        AllowCredentials: false
        AllowHeaders:
          - content-type
          - x-dupr-token
          - x-dupr-cookie
        AllowMethods:
          # Lambda Function URLs answer preflight automatically; OPTIONS is NOT a
          # valid enum value here (GET, PUT, HEAD, POST, PATCH, DELETE, *).
          - GET
          - POST
        AllowOrigins:
          - !Ref AllowedOrigin
        MaxAge: 3600

  FunctionUrlPermission:
    Type: AWS::Lambda::Permission
    Properties:
      FunctionName: !Ref LookupFunction
      Action: lambda:InvokeFunctionUrl
      Principal: '*'
      FunctionUrlAuthType: NONE
`;

// ── target B: API Gateway HTTP API ───────────────────────────────────────────

const apiGatewayResources = `  HttpApi:
    Type: AWS::ApiGatewayV2::Api
    Properties:
      Name: !Sub '\${AWS::StackName}-dupr-api'
      ProtocolType: HTTP
      CorsConfiguration:
        AllowCredentials: false
        AllowHeaders:
          - content-type
          - x-dupr-token
          - x-dupr-cookie
        # API Gateway answers the preflight itself; OPTIONS never reaches the function.
        AllowMethods:
          - GET
          - POST
        AllowOrigins:
          - !Ref AllowedOrigin
        MaxAge: 3600

  HttpApiIntegration:
    Type: AWS::ApiGatewayV2::Integration
    Properties:
      ApiId: !Ref HttpApi
      IntegrationType: AWS_PROXY
      IntegrationMethod: POST
      PayloadFormatVersion: '2.0'
      # API Gateway hard-caps a synchronous integration at 30 s regardless of the
      # Lambda timeout, which is why this template defaults Timeout to 29.
      TimeoutInMillis: 29000
      IntegrationUri: !Sub
        - 'arn:\${AWS::Partition}:apigateway:\${AWS::Region}:lambda:path/2015-03-31/functions/\${Fn}/invocations'
        - Fn: !GetAtt LookupFunction.Arn

  HttpApiDefaultRoute:
    Type: AWS::ApiGatewayV2::Route
    Properties:
      ApiId: !Ref HttpApi
      RouteKey: '$default'
      Target: !Sub 'integrations/\${HttpApiIntegration}'

  HttpApiStage:
    Type: AWS::ApiGatewayV2::Stage
    Properties:
      ApiId: !Ref HttpApi
      StageName: '$default'
      AutoDeploy: true

  HttpApiPermission:
    Type: AWS::Lambda::Permission
    Properties:
      FunctionName: !Ref LookupFunction
      Action: lambda:InvokeFunction
      Principal: apigateway.amazonaws.com
      SourceArn: !Sub 'arn:\${AWS::Partition}:execute-api:\${AWS::Region}:\${AWS::AccountId}:\${HttpApi}/*'
`;

// ── outputs ──────────────────────────────────────────────────────────────────

const outputs = ({ baseOutput, baseDescription, baseValue, subPrefix }) => `Outputs:
  ${baseOutput}:
    Description: ${baseDescription}
    Value: ${baseValue}

  SearchEndpoint:
    Description: GET a single name
    Value: !Sub '${subPrefix}api/search?q=John%20Doe'

  BulkEndpoint:
    Description: POST {"names":["John Doe","Jane Doe"]}
    Value: !Sub '${subPrefix}api/bulk'

  StatusEndpoint:
    Description: Cookie / cache status
    Value: !Sub '${subPrefix}api/status'

  TokenRequired:
    Description: Whether /api/* needs the x-dupr-token header
    Value: !If [TokenSet, 'yes - send x-dupr-token', 'no - endpoint is open']

Conditions:
  TokenSet: !Not [!Equals [!Ref ApiToken, '']]
`;

// ── assembly ─────────────────────────────────────────────────────────────────

const build = ({ description, params, resources, out }) => {
  const template = `AWSTemplateFormatVersion: '2010-09-09'
Description: >-
${description}

${parameters(params)}
Resources:
${coreResources}
${resources}
${outputs(out)}`;
  if (template.includes('${indent(')) throw new Error('template interpolation leaked');
  return template;
};

const functionUrlTemplate = build({
  description: `  DUPR lookup proxy for the CourtReserve watcher - one Lambda function behind a public
  Function URL that serves the lookup page at "/" and the /api/search, /api/bulk, /api/status
  and /api/verify endpoints. The DUPR session cookie is supplied as a stack parameter.`,
  params: { maxPages: 3, timeout: 60 },
  resources: functionUrlResources,
  out: {
    baseOutput: 'FunctionUrl',
    baseDescription: 'Base URL of the DUPR lookup service (page at /, API under /api/*)',
    baseValue: '!GetAtt FunctionUrl.FunctionUrl',
    subPrefix: '${FunctionUrl.FunctionUrl}',
  },
});

const apiGatewayTemplate = build({
  description: `  DUPR lookup API for the CourtReserve watcher - one Lambda function fronted by an
  API Gateway HTTP API (stage $default) exposing /api/search, /api/bulk, /api/status and
  /api/verify. The lookup page is hosted separately and points at the ApiBaseUrl output.`,
  params: {
    maxPages: 2,
    timeout: 29,
    cookieOptional: true,
    timeoutNote: ' API Gateway cuts the request off at 30 s, so 29 is the practical maximum.',
  },
  resources: apiGatewayResources,
  out: {
    baseOutput: 'ApiBaseUrl',
    baseDescription: 'Base URL of the API (no trailing slash) - paste into the page\'s Endpoint field',
    baseValue: '!Sub \'https://\${HttpApi}.execute-api.\${AWS::Region}.amazonaws.com\'',
    subPrefix: 'https://\${HttpApi}.execute-api.\${AWS::Region}.amazonaws.com/',
  },
});

for (const [file, template] of [
  [OUT_FUNCTION_URL, functionUrlTemplate],
  [OUT_API_GATEWAY, apiGatewayTemplate],
]) {
  fs.writeFileSync(file, template);
  const size = (fs.statSync(file).size / 1024).toFixed(1);
  console.log(`wrote ${path.relative(ROOT, file)} (${size} KB, inline code ${(code.length / 1024).toFixed(1)} KB)`);
}
